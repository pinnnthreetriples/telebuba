import { defineConfig, devices } from '@playwright/test';

// Визуальный гейт каталога, и он держит один порт — 8132.
//
// Порт назван, а не выбран автоматически, по причине из `.mex/context`: :8080 занят
// живым стендом, и снимать надо не его. Vite поднимается самим Playwright и гасится
// после прогона; `reuseExistingServer` оставлен включённым только вне CI, чтобы
// локальные повторные прогоны не ждали холодный старт.
//
// Один браузер и две ширины. Chromium — потому что снимок сравнивается сам с собой, а
// не с другим движком: цель гейта — заметить, что своя же правка сдвинула пиксель, и
// второй движок к этому вопросу ничего не добавляет, зато добавляет 250 МБ и второй
// набор эталонов. `deviceScaleFactor: 1` — чтобы эталоны не зависели от DPI машины.
export default defineConfig({
  testDir: './e2e',
  outputDir: './e2e/.artifacts',
  // Платформа и имя проекта в пути — оба обязательны, и оба выяснились падением.
  //
  // `{projectName}`: без него desktop и mobile пишут в один файл, и второй проект молча
  // перезаписывает эталон первого — гейт остаётся зелёным, проверяя одну ширину вместо
  // двух.
  //
  // `{platform}`: растеризация шрифта у Windows и Linux разная, и разная НЕ на глаз —
  // одна и та же кнопка мерит 126px на Windows и 125px на Linux при одном и том же файле
  // Inter. Эталоны, снятые локально, в CI не сходились ни одним разделом. Порог тут не
  // поможет: поднять его до пропуска однопиксельного сдвига текста значит перестать
  // видеть сдвиг ступени токена, то есть ровно то, зачем гейт есть.
  //
  // Поэтому у каждой платформы свой набор. Авторитетный — `linux`: на нём стоит CI, и
  // именно он блокирует merge. `win32` — локальное удобство: он даёт ту же проверку на
  // машине разработчика, но его расхождение с `linux` ничего не значит и никем не
  // сверяется. Обновлять после умышленного изменения внешности надо ОБА: локальный —
  // `npm run visual:update`, линуксовый — прогоном CI, который на первом падении
  // выкладывает сгенерированные эталоны артефактом `design-system-screenshots`.
  snapshotPathTemplate: '{testDir}/__screenshots__/{platform}/{projectName}/{arg}{ext}',
  fullyParallel: true,
  forbidOnly: Boolean(process.env.CI),
  retries: 0,
  reporter: process.env.CI ? 'line' : 'list',
  expect: {
    // Срок ожидания утверждения — тридцать секунд вместо пяти по умолчанию, и это не запас
    // «на всякий случай», а измеренная цифра.
    //
    // При `fullyParallel` четыре воркера открывают четыре разных маршрута одновременно, и
    // каждый ждёт, пока Vite ВПЕРВЫЕ соберёт граф модулей своего: холодный прогон занимает
    // 46 секунд против 19 на тёплом. На четырёх воркерах падало 2, 1 и 0 экранов от
    // прогона к прогону, на одном — 0 и 0. Раскладка так не ломается: она ломается
    // одинаково при любом числе воркеров. То есть срок упирался в сборку сервера, а не в
    // приложение, и гейт краснел не по своему поводу.
    //
    // Гейт, который перезапускают до зелёного, — не гейт. Ложное красное здесь обходится
    // дороже, чем долгое ожидание, и на успешном прогоне оно ничего не стоит: срок — это
    // предел, а не пауза.
    timeout: 30_000,
    // Порог в ДОЛЯХ площади здесь стоял и был неверен, а комментарий рядом утверждал
    // обратное: «0.2% заметно меньше, чем любой сдвиг ступени токена». 0.2% от снимка
    // 1280×2000 — это 5000 пикселей, и под ними прошли, ничего не сломав: сдвиг
    // раскрытой строки SurfHover на 48px, полоса залипшей шапки поверх раздела и правки
    // Modal с IconButton. Проверено принудительной перезаписью (`--update-snapshots=all`):
    // отличались ДВЕНАДЦАТЬ файлов, а падали два.
    //
    // Абсолютный порог вместо доли. Он покрывает то, ради чего порог вообще нужен —
    // единицы пикселей на границах глифов, — и не масштабируется вместе с площадью
    // страницы, из-за чего большой снимок и получал право на большое расхождение.
    // Сорок пикселей: это меньше площади одного глифа кегля 12px, то есть меньше любого
    // изменения, которое человек назвал бы изменением.
    //
    // Разделение эталонов по платформе (см. выше) — то, что делает такой порог возможным:
    // межплатформенная растеризация давала сотни пикселей, внутриплатформенная — единицы.
    //
    // Измерено, а не оценено: при пороге 0 три полных прогона подряд не дают НИ ОДНОГО
    // отличающегося пикселя ни в одном из снимков, а при 40 подряд прошло двадцать
    // прогонов. То есть внутриплатформенный шум здесь нулевой, и сорок — это запас, а не
    // допуск, который что-то съедает.
    //
    // Раньше в отчёте о правках 34, 31 и 2 отличающихся пикселя были названы шумом. Это
    // было неверно: они появились ОДИН раз — как остаток снятия `will-change` в съёмке, —
    // и от прогона к прогону не воспроизводятся. Разницу между «шум» и «разовое
    // следствие правки» видно только измерением, и порог, подобранный под первое,
    // прикрывает второе.
    toHaveScreenshot: {
      maxDiffPixels: 40,
      // Свой срок, короче общего: сравнение пикселей повторяется до совпадения, поэтому
      // тридцать секунд означали бы тридцать секунд на КАЖДЫЙ настоящий регресс. Десяти
      // хватает на стабилизацию страницы, а причина долгого ожидания выше — холодная
      // сборка маршрута — к моменту снимка уже прошла.
      timeout: 10_000,
      animations: 'disabled',
      // См. сам файл: снимает прилипание с шапки, которая иначе красится поверх снимка
      // раздела и прячет от гейта то, что под ней.
      stylePath: './e2e/screenshot.css',
    },
  },
  use: {
    baseURL: 'http://127.0.0.1:8132',
    deviceScaleFactor: 1,
    trace: 'retain-on-failure',
    // Растеризация текста — детерминированная, и это единственное, что делает порог в
    // сорок пикселей осмысленным.
    //
    // Найдено измерением, а не подбором. Разделение эталонов по платформе решало половину
    // задачи: внутри ОДНОГО прогона CI два снимка одного экрана побайтово равны (проверено
    // на девяти падавших: 0 отличающихся пикселей между `-actual` основного прогона и
    // пересозданным эталоном шага повтора). А против эталона, снятого ДРУГИМ прогоном,
    // те же снимки расходились на 19…100 пикселей — рассыпанных по краям глифов, при
    // визуально идентичной картинке.
    //
    // То есть «linux» — не один растеризатор: раннеры GitHub отличаются процессором и
    // содержимым образа, а хинтинг и субпиксельное позиционирование от этого зависят.
    // Порог тут не помогает: сто пикселей текста и сдвиг ступени токена — величины одного
    // порядка, и допуск, покрывающий первое, скрывает второе (ровно это и делал прежний
    // `maxDiffPixelRatio: 0.002`).
    //
    // Флаги убирают саму зависимость: без хинтинга и без субпиксельного позиционирования
    // глиф растеризуется одинаково на любом железе. Цена — однократная пересъёмка всех
    // эталонов и чуть более мягкие края букв на снимках; в приложении не меняется ничего,
    // потому что флаги живут только здесь.
    launchOptions: {
      args: [
        '--font-render-hinting=none',
        '--disable-font-subpixel-positioning',
        '--disable-lcd-text',
      ],
    },
  },
  projects: [
    {
      name: 'desktop',
      use: { ...devices['Desktop Chrome'], viewport: { width: 1280, height: 900 } },
    },
    {
      name: 'mobile',
      use: { ...devices['Desktop Chrome'], viewport: { width: 375, height: 812 } },
    },
  ],
  webServer: {
    command: 'npm run catalog',
    url: 'http://127.0.0.1:8132/catalog/',
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
});

import { defineConfig, devices } from '@playwright/test';

// Визуальный гейт каталога, и он держит один порт — 8132.
//
// Порт назван, а не выбран автоматически, по причине из `.mex/context`: :8080 занят
// живым стендом, и снимать надо не его. Vite поднимается самим Playwright и гасится
// после прогона; `reuseExistingServer` оставлен включённым только вне CI, чтобы
// локальные повторные прогоны не ждали холодный старт.
//
// Один браузер и две ширины. Chromium — потому что снимок сравнивается сам с собой, а
// не с другим движком: цель гейта — заметить, что своя же правка сдвинула пиксель, и
// второй движок к этому вопросу ничего не добавляет, зато добавляет 250 МБ и второй
// набор эталонов. `deviceScaleFactor: 1` — чтобы эталоны не зависели от DPI машины.
export default defineConfig({
  testDir: './e2e',
  outputDir: './e2e/.artifacts',
  // Платформа и имя проекта в пути — оба обязательны, и оба выяснились падением.
  //
  // `{projectName}`: без него desktop и mobile пишут в один файл, и второй проект молча
  // перезаписывает эталон первого — гейт остаётся зелёным, проверяя одну ширину вместо
  // двух.
  //
  // `{platform}`: растеризация шрифта у Windows и Linux разная, и разная НЕ на глаз —
  // одна и та же кнопка мерит 126px на Windows и 125px на Linux при одном и том же файле
  // Inter. Эталоны, снятые локально, в CI не сходились ни одним разделом. Порог тут не
  // поможет: поднять его до пропуска однопиксельного сдвига текста значит перестать
  // видеть сдвиг ступени токена, то есть ровно то, зачем гейт есть.
  //
  // Поэтому у каждой платформы свой набор. Авторитетный — `linux`: на нём стоит CI, и
  // именно он блокирует merge. `win32` — локальное удобство: он даёт ту же проверку на
  // машине разработчика, но его расхождение с `linux` ничего не значит и никем не
  // сверяется. Обновлять после умышленного изменения внешности надо ОБА: локальный —
  // `npm run visual:update`, линуксовый — прогоном CI, который на первом падении
  // выкладывает сгенерированные эталоны артефактом `design-system-screenshots`.
  snapshotPathTemplate: '{testDir}/__screenshots__/{platform}/{projectName}/{arg}{ext}',
  fullyParallel: true,
  forbidOnly: Boolean(process.env.CI),
  retries: 0,
  reporter: process.env.CI ? 'line' : 'list',
  expect: {
    // Сглаживание шрифтов даёт единицы отличающихся пикселей на одинаковой странице,
    // и нулевой порог превратил бы гейт в источник ложных падений. 0.2% от площади —
    // это заметно меньше, чем любой сдвиг ступени токена, и заметно больше, чем шум.
    toHaveScreenshot: {
      maxDiffPixelRatio: 0.002,
      animations: 'disabled',
      // См. сам файл: снимает прилипание с шапки, которая иначе красится поверх снимка
      // раздела и прячет от гейта то, что под ней.
      stylePath: './e2e/screenshot.css',
    },
  },
  use: {
    baseURL: 'http://127.0.0.1:8132',
    deviceScaleFactor: 1,
    trace: 'retain-on-failure',
  },
  projects: [
    {
      name: 'desktop',
      use: { ...devices['Desktop Chrome'], viewport: { width: 1280, height: 900 } },
    },
    {
      name: 'mobile',
      use: { ...devices['Desktop Chrome'], viewport: { width: 375, height: 812 } },
    },
  ],
  webServer: {
    command: 'npm run catalog',
    url: 'http://127.0.0.1:8132/catalog/',
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
});

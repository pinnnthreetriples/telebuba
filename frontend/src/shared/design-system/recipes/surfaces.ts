// Поверхности: белая коробка на подложке, и чем одна отличается от другой.
//
// Карточка, диалог, выпадающая панель и подсказка — одна и та же вещь на четырёх высотах,
// и рисовали её четырьмя способами. Тень была особенно показательной: выпадающий список,
// подсказка, тост и меню — всё это ПЛАВАЕТ над страницей, то есть одна роль, — и носили
// четыре разных тени. Теперь роль одна (`shadow-pop`), а варианты ниже говорят, чем
// поверхности действительно различаются: радиусом, наличием рамки и высотой.
import { cn } from '@/shared/lib/cn';

export const SURFACE = {
  // Карточка на странице: самый большой радиус, волосяная рамка, без тени — она лежит на
  // подложке, а не висит над ней.
  card: 'rounded-card border border-line bg-white',
  // Диалог: та же карточка, но над завесой, поэтому с тенью всплывающего.
  dialog: 'rounded-card bg-white shadow-pop',
  // Панель, вложенная в карточку: выпадающий список, меню, поповер. Радиус на ступень
  // меньше карточкиного — вложенная коробка с тем же радиусом читается как приклеенная.
  panel: 'rounded-lg border border-line bg-white shadow-pop',
  // Вдавленная область: лоток сегментированного контрола, зона перетаскивания. Не белая —
  // это единственная поверхность, которая уходит ВНУТРЬ.
  inset: 'rounded-lg bg-canvas',
  // Тёмная: терминал логов и подсказка, которая делит с ним чернила.
  inverse: 'rounded-lg bg-term text-term-text',
} as const;

export type SurfaceVariant = keyof typeof SURFACE;

export function surface(variant: SurfaceVariant, className?: string): string {
  return cn(SURFACE[variant], className);
}

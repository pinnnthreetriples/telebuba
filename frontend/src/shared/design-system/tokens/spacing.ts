// Ось расстояний: один ритм на все зазоры, отбивки и поля — и отдельно РАЗМЕРЫ, которые
// ритмом не являются.
//
// Разделение вынужденное и оно же главное решение этого файла. В Tailwind ключ
// `theme.spacing` становится и `p-<имя>`, и `w-<имя>`, поэтому пока таблица была одна, она
// отвечала на два разных вопроса — «сколько воздуха между вещами» и «какого размера
// вещь», — и 476 сайтов размеров тратили 73 разных значения, из которых 57 не называла ни
// одна ступень ритма. `width`, `height`, `size` и остальные объявлены своими шкалами
// именно поэтому: `p-md` красит 10px, а `w-md` не красит ничего.

// Ритм — одна шкала на все зазоры, отбивки и поля.
//
// ── Сетка ──────────────────────────────────────────────────────────────────────────
//
// 2, 4, 6, 8, 12, 16, 20, 24, 32, 64. Раньше здесь стояло 2, 3, 5, 7, 10, 14, 18, 22, 32,
// 64 — числа дизайн-источника. Они были ЛУЧШЕ произвольных, но сеткой не были: шаг между
// ступенями шёл 1, 2, 2, 3, 4, 4, 4, и предсказать следующую по предыдущей было нельзя.
// Хуже, что ни одна ступень из середины не делилась на 2 — элемент высотой 7px не
// центрируется в 22px без полупикселя, а полупиксель на экране это размытая граница.
//
// Ступеней десять, а не одиннадцать: 48px из сетки выпал, потому что его никто не носит,
// а ступень без носителя гейт мёртвых токенов справедливо отклоняет.
//
// Имена сохранены все: их набрано 1384 места, и переименование стоило бы 1384 правки, не
// сказав ничего нового. Что каждое означает: `hair` и `xs` разделяют сложенные волоски;
// `tight` — части одной вещи (точку и её подпись); `sm` — умолчание внутри контрола или
// строки; `md` — строки и поля внутри карточки; `lg` — блоки карточки или формы; `xl` и
// `2xl` — собственные горизонтальные поля контрола. `page` и `empty` принадлежат странице,
// а не тому, что на ней стоит, и носят имена вместо величин: компонент, тянущийся за самым
// большим числом, — это ровно то, как они тратились, и `p-page` на карточке читается как
// ошибка там, где `p-4xl` читался как размер.

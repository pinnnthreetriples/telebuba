// ритмом не являются.
//
// Разделение вынужденное и оно же главное решение этого файла. В Tailwind ключ
// `theme.spacing` становится и `p-<имя>`, и `w-<имя>`, поэтому пока таблица была одна, она
// отвечала на два разных вопроса — «сколько воздуха между вещами» и «какого размера
// вещь», — и 476 сайтов размеров тратили 73 разных значения, из которых 57 не называла ни
// одна ступень ритма. `width`, `height`, `size` и остальные объявлены своими шкалами
// именно поэтому: `p-3` красит 12px, а `w-3` не красит ничего. В Tailwind 4 это держит
// генератор темы: ритм не объявлен в `--spacing-*`, куда размеры откатываются, а только в
// пространствах отступов и зазоров (`scripts/configScales.mjs`, `THEME_NAMESPACES`), и
// `closedScales.test.ts` проверяет, что `w-3` по-прежнему молчит.

// Ритм — одна шкала на все зазоры, отбивки и поля.
//
// ── Сетка Firecrawl ────────────────────────────────────────────────────────────────
//
// Основание 4px, ключ — число шагов: `1` = 4px, `4` = 16px, `16` = 64px. Шкала и её
// каденция взяты у Firecrawl целиком: 8px внутри группы, 16px между группами, 24px — поле
// карточки (16 у компактной), 32–40px — между секциями.
//
// Прежние имена-роли (`tight`, `md`, `2xl`, `page`…) ушли, и это не потеря смысла: роль
// жила в имени, а значение — в сетке, и три ступени из десяти (`hair` 2px, `tight` 6px,
// `xl` 20px) в сетку 4px не ложились вовсе. Число говорит ровно то, что красит, а роль
// говорит место, где оно стоит, — рецепт или компонент.
//
// Ступени объявлены только те, что кто-то носит: 40px (`10`) и 96px (`24`) у Firecrawl
// есть, но носителя у них нет, и гейт мёртвых токенов отклонил бы их. `0` — не ступень,
// а отсутствие отступа.
//
// Волоска `px` (1px) в сетке больше нет — ни здесь, ни в ширинах и высотах. Он подтягивал
// подпись под заголовок, добавлял поле плашке и рисовал разделители щелью в 1px; первые
// два сдвига в сетку 4px не ложились и сняты, а линия — это граница (`border-*`), не
// отступ и не размер.

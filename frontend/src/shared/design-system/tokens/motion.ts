// Ось движения: четыре длительности и две кривые.
//
// Жест, растянутый на два элемента, обязан тратить ОДИН рунг на обе половины — панель
// выпадающего списка и её шеврон шли 420ms против 400ms, а это 20ms расхождения, которых
// никто не выбирал.
//
// ── Про ключ `DEFAULT`, и это не деталь ────────────────────────────────────────────
//
// `transitionDuration` и `transitionTimingFunction` стоят в корне `theme`, то есть
// ЗАМЕНЯЮТ шкалы Tailwind — вместе с их ключами `DEFAULT`. Tailwind впекает эти два
// умолчания в каждую утилиту `transition-*`, поэтому замена шкалы без `DEFAULT` выпускает
// `.transition-colors` со свойством и без длительности, а начальная длительность в CSS —
// 0s. Коммит, сделавший эти токены авторитетными, — это коммит, выключивший 25 переходов
// приложения; шесть гейтов были зелёными над ним сутки, потому что не идущий переход — не
// сырое значение, не провал контраста и не расхождение с документом. `motion.test.ts`
// компилирует настоящий `index.css` и проверяет, что длительность выходит: единственная
// форма проверки, которая это ловит. В Tailwind 4 те же два умолчания называются
// `--default-transition-duration` и `--default-transition-timing-function`, и
// `scripts/tailwind-theme.mjs` пишет их из этих `DEFAULT`.

// ── Рунги: их стало больше, и вот почему ───────────────────────────────────────────
//
// Четыре доставали до ПЕРЕХОДОВ и ни до чего больше: `index.css` тратил тринадцать сырых
// длительностей в сокращениях `animation:`, а восемь утилит `[animation:…]` в пяти
// компонентах — ещё четыре. Правило линтера банило `duration-[` и не доставало ни до
// одной из них, и предыдущая заметка на этом месте это честно записывала как открытое.
//
// Закрыто консолидацией по ЖЕСТУ, а не введением рунга под каждое число:
//
//   `swap`  340ms — вещь меняется на другую вещь на месте: подмена аватара (0.34s),
//                   галочка «сохранено» (0.35s), подмена содержимого карточки (0.32s).
//                   Три носителя, разброс 30ms — расхождение, а не три решения.
//   `spin`  800ms — кольцо крутится: два спиннера приложения шли 0.7s и 0.85s.
//   `pulse` 1200ms — вещь дышит на месте, бесконечно: пять носителей на 1.1, 1.2, 1.2,
//                   1.4 и 2s. Две тысячи были самой медленной и единственной; жест у всех
//                   пяти один.
//   `roll`  900ms — значение доезжает до себя: одометр и полоса, заполняющаяся до своей
//                   доли (шла 1.7s). Оба — «число прибывает», и это одна работа.
//
// `enter` вобрал 0.24s шторки к своим 0.25s, `reveal` — 0.4s всплытия к своим 420ms: по
// 10 и 20 миллисекунд, то есть меньше кадра при 60 Гц.
export const duration = {
  DEFAULT: '150ms',
  // Наведение или смена краски: то, что уже на экране, реагирует.
  state: '150ms',
  // Что-то приезжает: тост, шторка, проявление непрозрачности.
  enter: '250ms',
  // Вещь меняется на другую вещь на своём месте.
  swap: '340ms',
  // Панель раскрывается — и каждая часть этого жеста, шеврон включительно.
  reveal: '420ms',
  // Кольцо крутится.
  spin: '800ms',
  // Значение доезжает до себя: одометр, полоса до своей доли.
  roll: '900ms',
  // Вещь дышит на месте, бесконечно.
  pulse: '1200ms',
  // Задержка второй половины парной подмены: старое значение уходит, новое приходит на
  // 90ms позже, и эта разница — то, что делает подмену читаемой, а не мерцанием. Не
  // длительность, а сдвиг, и живёт здесь потому, что тратится тем же сокращением
  // `animation:`. Носителей два — оба диалога, где сохранённое значение подменяется.
  stagger: '90ms',
} as const;

// Четыре кривые, и две из них — про анимацию, а не про переход.
//
// `out` намеренно берёт имя `ease-out`, чтобы единственная «оседающая» кривая приложения
// была той, за которой компонент тянется: резко замедляется и встаёт (рельс заполняется,
// число крутится). `spring` слегка перелетает и садится назад (панель раскрывается,
// шеврон переворачивается).
//
// `linear` и `breathe` появились вместе с рунгами анимаций: сокращения `animation:`
// тратили `linear`, `ease`, `ease-out` и `ease-in-out` — ключевые слова CSS, которые
// правило линтера не отличает от забытой кривой. Теперь их четыре имени, и все четыре
// названы жестом.
// Press feedback stays small enough to avoid moving the control's layout.
export const pressScale = {
  rest: '1',
  press: '0.96',
} as const;

export const easing = {
  // См. заметку про `duration.DEFAULT`: без этого ключа каждая утилита `transition-*`
  // теряет и кривую тоже.
  DEFAULT: 'cubic-bezier(.16,1,.3,1)',
  out: 'cubic-bezier(.16,1,.3,1)',
  spring: 'cubic-bezier(.34,1.45,.6,1)',
  // Равномерная, и она нужна ровно одному жесту — вращению. Кривая на бесконечном
  // вращении видна как рывок на каждом обороте, поэтому `linear` здесь не отсутствие
  // решения, а решение. Ступень есть, чтобы `linear` в таблице стилей был токеном, а не
  // ключевым словом CSS, которое правило линтера не отличит от забытого.
  linear: 'linear',
  // Дыхание: вещь уходит и возвращается, и обе половины должны замедляться. Носителей
  // три — пульс текста, пульс загрузки, точка «печатает…».
  breathe: 'cubic-bezier(.4,0,.6,1)',
} as const;

// ── Движение в JavaScript: те же жесты, сказанные для `motion` ─────────────────────
//
// Три компонента `shared/ui` (DeleteButton, InlineTimeEdit, DateRangePicker) пришли из
// Devigner UI и двигаются библиотекой `motion`, а не переходами CSS: крышка корзины
// поворачивается на петле, плашка разъезжается из одной пилюли в три, кружок даты
// перелетает к соседнему дню. Такое движение считает физика (пружина) или часы (твин),
// и у библиотеки свой формат — объект, а не строка `cubic-bezier(…)`.
//
// Числа здесь — второй язык ТОЙ ЖЕ оси, а не вторая ось. Поэтому твины не пишут своих
// длительностей и кривых, а берут рунги выше: `follow` — это `state`, `fade` — `enter`,
// `roll` и `draw` — `swap`, все на `out` (кроме пера, которое идёт по `linear`). Пружины
// длительности не имеют вовсе — их время следует из жёсткости, затухания и массы, — и это
// единственные новые числа: три пружины Devigner, перенесённые как есть, потому что именно
// они делают его анимации его анимациями.

// Кривая `out` в форме, которую читает `motion`. Строка `easing.out` и этот массив — одно
// решение, и `tokens.test.ts` держит их вместе.
export const curve = {
  out: [0.16, 1, 0.3, 1],
} as const;

const seconds = (rung: string): number => Number.parseFloat(rung) / 1000;

export const spring = {
  // Коробка меняет форму или место: корзина раздвигается под плашку подтверждения,
  // время распадается на три плитки и складывается обратно, кружок даты и подчёркивание
  // поля перелетают. Самая мягкая из трёх: геометрия должна доехать, не дрогнув.
  layout: { type: 'spring', stiffness: 360, damping: 32, mass: 0.6 },
  // Вещь сменяется другой вещью на месте — то же, что рунг `swap`, но с инерцией:
  // крышка корзины, кнопки плашки, глиф «изменить» ↔ «сохранить».
  swap: { type: 'spring', stiffness: 460, damping: 30, mass: 0.55 },
  // Нажатие — пружинная половина `pressScale`: сжатие до `press` и возврат к `rest`.
  // Самая жёсткая, потому что палец уже отпустил, а контрол ещё не вернулся.
  press: { type: 'spring', stiffness: 500, damping: 30, mass: 0.6 },
} as const;

export const tween = {
  // Полоса диапазона дат тянется за курсором через много дней в секунду. Без инерции:
  // всё, у чего она есть, перелетает строку или отстаёт от указателя. `state` на `out`.
  follow: { duration: seconds(duration.state), ease: curve.out },
  // Вспомогательная краска приходит и уходит: тень плитки, единицы «ч»/«мин». `enter`.
  fade: { duration: seconds(duration.enter), ease: curve.out },
  // Значение доезжает до нового на своём месте: подпись «3 ночи» в плашке. `swap`.
  roll: { duration: seconds(duration.swap), ease: curve.out },
  // Перо рисует глиф штрихом — корзину, галочку. Перо идёт с постоянной скоростью, и
  // любая кривая съедала бы хвост штриха, поэтому `linear`; длительность — `swap`, а
  // вторая половина подмены приходит на `stagger` позже.
  draw: { duration: seconds(duration.swap), ease: 'linear' },
  handoff: seconds(duration.stagger),
} as const;

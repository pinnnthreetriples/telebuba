// Уровень 1. Настоящие значения — и каждое написано здесь ровно один раз.
//
// Почему уровнем ниже Tailwind, а не в самом конфиге: значения нужны ТРЁМ потребителям, и
// один из них не может импортировать конфиг. `tailwind.config.ts` собирает из них темы,
// но он же импортирует `tailwindcss/plugin`; `src/shared/lib/cn.ts` — код приложения, и
// импорт конфига затащил бы плагин Tailwind в браузерный бандл. Пока значения жили в
// конфиге, `cn.ts` держал их СПИСКОМ — двенадцать ступеней ритма, восемь рунгов размера,
// двенадцать ролей, — и это был шестой экземпляр тех же имён, самый опасный из всех:
// разойдясь, он не красит ничего неправильно, а перестаёт разрешать конфликт классов, и
// перекрытие, переданное вызывающим, молча выбрасывается.
//
// Эти файлы не импортируют ничего, кроме друг друга. Отсюда их может прочитать и конфиг,
// и приложение, и — текстом — гейты в `scripts/`.
//
// Разделение по файлам: здесь то, что не является отдельной осью — палитра, радиусы,
// тени, слои. Ось со своим набором решений держит свои значения сама: `typography.ts`,
// `spacing.ts`, `motion.ts`. Причина простая: у оси есть правило, по которому её ступени
// сходятся, и правило должно лежать рядом со ступенями, а не через файл от них.


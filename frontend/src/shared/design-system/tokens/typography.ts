// Ось типографики: ступени размера, роли, межстрочное и межбуквенное.
//
// Роль — это то, чем текст является читателю; ступень — то, какого он размера. Страница
// называет роль, а `shared/ui` тратит ступень: набор ступеней рядом с весом и серым, а не
// роль, — это то, как одна работа получила три написания (подпись была `ink-subtle` 57
// раз, `ink-muted` 13 и без краски 9).
//
// Краска роли — ИМЯ семантической ступени, не значение: роль не может разойтись с
// палитрой, потому что не хранит её.
//
// Межстрочное не входит в ступень РАЗМЕРА (см. ниже), но входит в РОЛЬ, и это разные
// решения. Роль, которая не называет свой интерлиньяж, зависит от предка: `type-caption`
// внутри контейнера с `leading-log` молча разъезжается на 1.85, и роль перестаёт быть тем,
// чем выглядит. Теперь каждая роль называет его сама.
//
// У всех двенадцати он `body` — потому что именно так они и рисуются СЕЙЧАС: раньше это
// значение приходило от `body` наследованием. То есть правка ничего не двигает на экране, а
// закрывает роль: пиксели те же, авторитет другой. Два сайта, которые перекрывают
// интерлиньяж утилитой (`type-item-title leading-stack`, `type-card-title leading-stack`),
// продолжают работать: роли выпускаются в слой `components`, утилита его выигрывает. Раньше телесный интерлиньяж приложения не был написан
// нигде: его ставил `html { line-height: 1.5 }` из preflight Tailwind, всё его
// наследовало, и предыдущая заметка на этом месте объясняла, почему ступени для него нет —
// «ей нечего носить». Довод был неверный: носить её должен `body`, а «значение приходит из
// умолчания зависимости» — это не единый источник правды, а его отсутствие, замаскированное
// тем, что умолчание совпало с желаемым.
//
// Ступени остаются голыми строками (без пары `[размер, интерлиньяж]`): вписать интерлиньяж
// в рунг значило бы молча переверстать каждый сайт, который на этот рунг перешёл.

// ── Шесть ступеней, и раньше их было восемь ────────────────────────────────────────
//
// Ушли `micro` (10.5px) и `lead` (13px), и ушли потому, что были не ступенями, а
// полушагами: 10.5 против 11 — половина пикселя, 12.5 против 13 — тоже. Полшага не
// решение: их не различить иначе, чем измерив, и в 91 месте приложения они стояли там,
// где легла рука. `micro` слился в `tiny`, `lead` — в `body`.
//
// Основной читаемый размер поднят до 14px. Это операторский дашборд, и 12.5px был
// сознательно плотным — но плотность бралась из кегля, самого дорогого места, где её
// можно взять. Плотность несёт ритм отступов; кегль должен читаться.
//
// `tiny` поднят до 12px по той же причине: 11px — размер, на котором подпись перестаёт
// читаться с первой попытки, а подпись — самая частая роль приложения.
export const fontSize = {
  // Подпись, ярлык плашки, шапка таблицы, строка журнала.
  tiny: '12px',
  // Основной размер интерфейса: всё внутри карточки, собственный текст контрола.
  body: '14px',
  // Заголовок карточки или диалога.
  title: '16px',
  // Число одометра.
  stat: '20px',
  // Заголовок страницы.
  display: '22px',
  // Единственная цифра пустого состояния.
  hero: '42px',
} as const;

// ── Двенадцать ролей ───────────────────────────────────────────────────────────────
//
// Ушла `meta`, и ушла как следствие слияния ступеней: она отличалась от `caption` РОВНО
// размером (`micro` против `tiny`) — тот же вес, тот же серый. Слив ступени, две роли
// стали побайтово одинаковыми, а роль, которая рисуется как другая, — не роль, а синоним.
// Двадцать её носителей теперь `caption`.
//

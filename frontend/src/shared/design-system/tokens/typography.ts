// Ось типографики: пять ступеней размера, два веса и семь стилей текста.
//
// Ступень — это размер ВМЕСТЕ со своим интерлиньяжем и трекингом: `text-body` ставит
// 14px, 20px и −0.006em одним классом. Стиль (`type-*`) — это ступень плюс вес плюс
// краска по умолчанию; страница называет стиль, а `shared/ui` тратит ступень и решает вес
// и краску сам.
//
// Шкала сведена так, чтобы каждый размер был ОДНИМ уровнем иерархии. Прежде их было шесть
// (12, 14, 16, 20, 22, 42) при двенадцати ролях и четырёх весах: 20 и 22 жирным на экране
// не различались, заголовок диалога отличался от заголовка карточки только весом, а пять
// ролей по 14px — тремя оттенками серого. Теперь иерархию несёт размер, вес — только
// «текст» (400) или «название» (500), краска — отдельная ось.
//
// Краска стиля — ИМЯ семантической ступени, не значение: стиль не может разойтись с
// палитрой, потому что не хранит её. Цвет поверх стиля пишется утилитой:
// `type-body text-content-subtle`, `type-small text-danger`.

// ── Ступени ───────────────────────────────────────────────────────────────────────
//
// Шаг между соседями не меньше 14%, интерлиньяж кратен 4px. Трекинг — оптический, по
// формуле Inter Dynamic Metrics (−0.0223 + 0.185·e^(−0.1745·размер), em): крупное
// собирается, мелкое остаётся свободным. 12px по формуле даёт 0.0005em, то есть ноль.
export const typeScale = {
  // Подпись, плашка, шапка таблицы, строка журнала.
  small: { size: '12px', leading: '16px', tracking: '0em' },
  // Весь текст интерфейса: проза, значения, названия, подписи полей, кнопки.
  body: { size: '14px', leading: '20px', tracking: '-0.006em' },
  // Заголовок карточки.
  h3: { size: '16px', leading: '24px', tracking: '-0.011em' },
  // Заголовок диалога.
  h2: { size: '20px', leading: '28px', tracking: '-0.017em' },
  // Заголовок страницы и число счётчика.
  h1: { size: '24px', leading: '32px', tracking: '-0.019em' },
} as const;

// Размер ступени отдельно — для потребителей, которым нужно только число (гейты,
// документация). Tailwind получает ступень целиком, парой с интерлиньяжем и трекингом:
// см. `tailwind.config.ts`.
export const fontSize = Object.fromEntries(
  Object.entries(typeScale).map(([name, step]) => [name, step.size]),
) as { [K in keyof typeof typeScale]: (typeof typeScale)[K]['size'] };

// Два веса, и шкала Tailwind заменена ими целиком: `font-semibold` и `font-bold` не
// выпускают ничего. 400 — то, что читают; 500 — то, что называют: заголовок, название
// элемента, подпись поля, кнопку. Жирность больше не делает иерархию — её делает размер.
export const fontWeight = {
  normal: '400',
  medium: '500',
} as const;

// ── Стили ─────────────────────────────────────────────────────────────────────────
//
// Семь стилей на пять ступеней: две ступени (`body`, `small`) бывают в двух весах, и это
// не дубль, а пара «текст — название». Краска по умолчанию закреплена за уровнем, раз вес
// больше не несёт контраст: заголовки и названия — `primary`, текст — `secondary`,
// мелкое — `subtle`.
export const typeRole = {
  h1: { size: 'h1', weight: 'medium', ink: 'content-primary' },
  h2: { size: 'h2', weight: 'medium', ink: 'content-primary' },
  h3: { size: 'h3', weight: 'medium', ink: 'content-primary' },
  body: { size: 'body', weight: 'normal', ink: 'content-secondary' },
  'body-medium': { size: 'body', weight: 'medium', ink: 'content-primary' },
  small: { size: 'small', weight: 'normal', ink: 'content-subtle' },
  'small-medium': { size: 'small', weight: 'medium', ink: 'content-subtle' },
} as const;

// Интерлиньяж живёт в ступени; отдельной шкалой остался только глиф. `none` — не строка
// текста, а один символ: `×`, снимающий чип, `?` подсказки.
export const lineHeight = {
  none: '1',
} as const;

// Не шкала. Трекинг текста живёт в ступени; `code` — не типографика, а АФФОРДАНС поля:
// расстояние, которое позволяет читать одноразовый код по символам, пока его набирают.
export const letterSpacing = {
  code: '0.18em',
} as const;

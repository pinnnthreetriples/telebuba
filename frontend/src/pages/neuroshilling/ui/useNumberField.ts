import { useState } from 'react';

/** Числовое поле, которое можно ОПУСТОШИТЬ, не потеряв значение в черновике.
 *
 * Управляемое `<input type="number">`, зажимающее значение на каждом нажатии, ломается
 * одинаково во всех местах: `Number('')` — это ноль, поэтому стёртое поле немедленно
 * переписывается нулём, курсор встаёт после него, и следующие цифры дописываются к нему.
 * Оператор, стирающий «60», чтобы набрать «180», получает «0180» и не может это
 * исправить, не выделив всё заново.
 *
 * Пустая строка здесь остаётся пустой строкой и в черновик не уезжает: там продолжает
 * лежать прежнее число. На потере фокуса собственный текст сбрасывается, поэтому поле,
 * брошенное пустым, возвращает сохранённое значение, а не ноль.
 *
 * А вот выход ЗА ГРАНИЦУ зажимается сразу и виден сразу: набранное «99999» становится
 * «3600» на том же нажатии. Это не то же самое, что пустота — там значения ещё нет, а
 * здесь оно есть и оно недопустимо; показать его непоправленным значило бы обещать
 * сохранение того, что уедет другим.
 *
 * Хук, а не компонент: одну и ту же пару держат и голые `<input>` внутри пилюли паузы, и
 * `Input` дизайн-системы в диалоге лимитов. Общее у них поведение, а не оболочка.
 */
export function useNumberField(
  value: number,
  clamp: (raw: number) => number,
  commit: (next: number) => void,
): {
  value: string;
  onChange: (raw: string) => void;
  onBlur: () => void;
} {
  const [text, setText] = useState<string | null>(null);
  return {
    value: text ?? String(value),
    onChange: (raw) => {
      // Пустое и промежуточное («-», «1e») в черновик не уезжают: там лежит прежнее
      // число, и до набранного оно так и лежит.
      if (raw.trim() === '' || !Number.isFinite(Number(raw))) {
        setText(raw);
        return;
      }
      const next = clamp(Number(raw));
      commit(next);
      // Показывается зажатое, а не набранное, — но только когда зажим что-то изменил:
      // иначе «060» на пути к «60» переписывалось бы в «60» с прыжком курсора.
      setText(next === Number(raw) ? raw : String(next));
    },
    onBlur: () => {
      setText(null);
    },
  };
}
